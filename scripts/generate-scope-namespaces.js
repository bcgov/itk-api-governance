#!/usr/bin/env node
// Builds the SDX scope namespace allowlist used by the SDX R1 ruleset.
//
// Combines:
//   - the lowercase member IDs from the SDX organization onboarding list
//     (api-serv-infra .sdx/org-onboarding/organizations.yaml), and
//   - the hand-maintained namespaces in managed-namespaces.yaml.
//
// Usage:
//   npm run generate-scope-namespaces [-- <path/to/organizations.yaml>]
//
// The organizations path defaults to ../api-serv-infra/.sdx/org-onboarding/
// organizations.yaml, or SDX_ORGANIZATIONS_FILE when it is set.

import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const NAMESPACE_DIR = path.resolve('__main__/src/yaml/spectral/sdx-scope-namespaces');
const MANAGED_FILE = path.join(NAMESPACE_DIR, 'managed-namespaces.yaml');
const OUTPUT_FILE = path.join(NAMESPACE_DIR, 'scope-namespaces.yaml');
const DEFAULT_ORGANIZATIONS_FILE = path.resolve('../api-serv-infra/.sdx/org-onboarding/organizations.yaml');
const IDENTIFIER = /^[a-z][a-z0-9_-]*$/;

const organizationsFile = path.resolve(
  process.argv[2] || process.env.SDX_ORGANIZATIONS_FILE || DEFAULT_ORGANIZATIONS_FILE,
);

function fail(message) {
  console.error(`✖ ${message}`);
  process.exit(1);
}

function readYaml(file) {
  if (!fs.existsSync(file)) fail(`File not found: ${file}`);
  return yaml.load(fs.readFileSync(file, 'utf8'));
}

function memberIdOf(org) {
  const tag = (org.tags || []).find((t) => typeof t === 'string' && t.startsWith('member_id:'));
  return tag ? tag.slice('member_id:'.length).trim() : undefined;
}

const entries = new Map(); // namespace -> comment
const errors = [];

for (const org of readYaml(organizationsFile)?.organizations || []) {
  const memberId = memberIdOf(org);
  if (!memberId) {
    errors.push(`Organization "${org.name}" has no member_id tag.`);
    continue;
  }
  const namespace = memberId.toLowerCase();
  if (!IDENTIFIER.test(namespace)) {
    errors.push(`Member ID "${memberId}" (${org.name}) is not a valid scope namespace.`);
    continue;
  }
  if (entries.has(namespace)) {
    errors.push(`Member ID "${memberId}" appears more than once.`);
    continue;
  }
  entries.set(namespace, `${memberId}: ${org.title || org.name}`);
}

for (const item of readYaml(MANAGED_FILE)?.namespaces || []) {
  const namespace = item?.namespace;
  if (typeof namespace !== 'string' || !IDENTIFIER.test(namespace)) {
    errors.push(`Managed namespace "${namespace}" is not a valid scope namespace.`);
    continue;
  }
  if (entries.has(namespace)) {
    errors.push(`Managed namespace "${namespace}" is already an organization member ID; remove it from managed-namespaces.yaml.`);
    continue;
  }
  entries.set(namespace, `managed: ${item.description || 'no description'}`);
}

if (errors.length > 0) fail(`Cannot build the namespace list:\n  ${errors.join('\n  ')}`);

const lines = [
  '# Generated by scripts/generate-scope-namespaces.js. Do not edit by hand.',
  '# Sources: SDX organization member IDs (lowercase) and managed-namespaces.yaml.',
  '# To add a namespace, edit managed-namespaces.yaml and run',
  '# `npm run generate-scope-namespaces`.',
  'namespaces:',
  ...[...entries.keys()].sort().map((ns) => `  - ${ns} # ${entries.get(ns).replace(/\s+/g, ' ')}`),
  '',
];

fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');
console.log(`✔ Wrote ${entries.size} namespaces to ${path.relative(process.cwd(), OUTPUT_FILE)}`);
